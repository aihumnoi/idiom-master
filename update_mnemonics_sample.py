with open("app/data/oxford3000.json", encoding="utf-8") as f:
    ox = json.load(f)

updated = 0
for item in ox:
    lemma = item.get("lemma")
    if lemma in mnemonics_20:
        item["mnemonic"] = mnemonics_20[lemma]
        updated += 1

with open("app/data/oxford3000.json", "w", encoding="utf-8") as f:
    json.dump(ox, f, ensure_ascii=False, indent=2)

with open("app/data/oxford3000.js", "w", encoding="utf-8") as f:
    f.write("window.__OXFORD__ = " + json.dumps(ox, ensure_ascii=False, indent=2) + ";\n")

print(f"Successfully updated {updated} items with vivid story mnemonics!")
